// Papyrus is Light with its colors multiplied by parchment, so everything Light
// styles is styled in Papyrus too and the two never drift apart.
//
//   node scripts/papyrus.js          rewrites the generated block in styles.css and pocket/www/pocket.css
//   node scripts/papyrus.js --check  exits 1 if either block is out of date (no files written)
//
// Every top-level rule whose selector starts with `body.light` gets a copy that starts
// with `body.papyrus`, its colors tinted. Rules written by hand for Papyrus
// (the "PAPYRUS (View → Page → Papyrus)" section) come later and win.

'use strict';

const fs = require('fs');
const path = require('path');

const BEGIN = '/* PAPYRUS:BEGIN (generated by scripts/papyrus.js from the body.light rules above; do not edit) */';
const END = '/* PAPYRUS:END */';
const TINT = [0xf6, 0xed, 0xd3]; // the parchment: white × this = the page's color

const hex2 = (n) => Math.max(0, Math.min(255, Math.round(n))).toString(16).padStart(2, '0');
const tint = ([r, g, b]) => [r * TINT[0] / 255, g * TINT[1] / 255, b * TINT[2] / 255];

function tintColors(text) {
  return text
    .replace(/#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b/g, (m, h) => {
      if (h.length === 3) h = h.split('').map((c) => c + c).join('');
      const [r, g, b] = tint([0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)));
      return '#' + hex2(r) + hex2(g) + hex2(b) + h.slice(6);
    })
    .replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(,\s*[\d.]+\s*)?\)/g, (m, r, g, b, a) => {
      const [tr, tg, tb] = tint([+r, +g, +b]);
      return (a ? 'rgba(' : 'rgb(') + [tr, tg, tb].map(Math.round).join(', ') + (a ? a.replace(/\s+/g, ' ').replace(',', ',') : '') + ')';
    });
}

// the top-level rules of a stylesheet: [{ selector, body }]; @-blocks are skipped whole
function topRules(css) {
  const rules = [];
  let i = 0;
  while (i < css.length) {
    if (css.startsWith('/*', i)) { const e = css.indexOf('*/', i + 2); i = e < 0 ? css.length : e + 2; continue; }
    const open = css.indexOf('{', i);
    if (open < 0) break;
    let head = css.slice(i, open);
    // comments inside the selector text
    head = head.replace(/\/\*[\s\S]*?\*\//g, '');
    let depth = 1, j = open + 1;
    while (j < css.length && depth) {
      if (css.startsWith('/*', j)) { const e = css.indexOf('*/', j + 2); j = e < 0 ? css.length : e + 2; continue; }
      if (css[j] === '{') depth++;
      else if (css[j] === '}') depth--;
      j++;
    }
    const selector = head.trim();
    const body = css.slice(open + 1, j - 1);
    if (selector && !selector.startsWith('@')) rules.push({ selector, body });
    i = j;
  }
  return rules;
}

function generate(css) {
  const out = [];
  for (const { selector, body } of topRules(css)) {
    const parts = selector.split(',').map((s) => s.trim()).filter((s) => /^body\.light(?![\w-])/.test(s));
    if (!parts.length) continue;
    const sel = parts.map((s) => s.replace(/^body\.light(?![\w-])/, 'body.papyrus')).join(', ');
    const decl = tintColors(body.replace(/\s+/g, ' ').trim());
    if (decl === body.replace(/\s+/g, ' ').trim()) continue; // no colors: nothing to re-tone
    out.push(`${sel} { ${decl} }`);
  }
  return out;
}

function stripBlock(css) {
  const a = css.indexOf(BEGIN);
  if (a < 0) return { css, at: -1 };
  const b = css.indexOf(END, a);
  return { css: css.slice(0, a) + css.slice(b + END.length).replace(/^\n+/, ''), at: a };
}

function build(file, anchorText) {
  const src = fs.readFileSync(file, 'utf8');
  const { css: bare, at } = stripBlock(src);
  const rules = generate(bare);
  const block = `${BEGIN}\n${rules.join('\n')}\n${END}\n`;
  let insertAt = at;
  if (insertAt < 0) {
    insertAt = anchorText ? bare.indexOf(anchorText) : bare.length;
    if (insertAt < 0) throw new Error(`${file}: no place for the Papyrus block (looked for ${JSON.stringify(anchorText)})`);
    // before the anchor's own comment banner, if it has one
    const banner = bare.lastIndexOf('/* ====', insertAt);
    if (anchorText && banner >= 0 && insertAt - banner < 400) insertAt = banner;
  }
  const next = bare.slice(0, insertAt) + block + '\n' + bare.slice(insertAt);
  return { src, next, count: rules.length };
}

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [file, anchor] of [
    [path.join(root, 'styles.css'), 'PAPYRUS (View → Page → Papyrus)'],
    [path.join(root, 'pocket/www/pocket.css'), null]
  ]) {
    const { src, next, count } = build(file, anchor);
    if (check) { if (src !== next) { stale = true; console.log('out of date: ' + path.relative(root, file)); } continue; }
    if (src !== next) fs.writeFileSync(file, next);
    console.log(`${path.relative(root, file)}: ${count} Papyrus rules from the Light rules`);
  }
  if (check && stale) process.exit(1);
}

module.exports = { tintColors, generate, topRules };
